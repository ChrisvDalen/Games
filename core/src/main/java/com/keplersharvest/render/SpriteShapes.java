/**
 * Hand-drawn 16x16 sprite shapes, stored as palette indices rather than colours.
 *
 * <p>Each row is sixteen characters:
 * <ul>
 *   <li>{@code .} transparent</li>
 *   <li>{@code 0} outline, the darkest tone</li>
 *   <li>{@code 1} shade</li>
 *   <li>{@code 2} base - the colour the content file declares</li>
 *   <li>{@code 3} highlight</li>
 *   <li>{@code 4} accent, used for lit screens, ripe fruit and visors</li>
 * </ul>
 *
 * <p>Keeping shape and colour apart is what stops this table from exploding: one crop shape serves
 * all four crops, one module shape serves all three modules, and a new crop needs a colour in JSON
 * rather than new artwork. {@link WorldSprites} turns a shape plus a base colour into a texture.
 *
 * <p>Sprites are 16x16 and drawn two world units per pixel, so world pixels are twice the size of
 * interface pixels - chunky world art, finer interface text.
 */
