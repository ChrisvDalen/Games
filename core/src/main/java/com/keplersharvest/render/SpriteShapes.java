    private SpriteShapes() {
    }

    public static String[] rows(String id) {
        String[] rows = SHAPES.get(id);
        if (rows == null) {
            throw new IllegalArgumentException("Unknown sprite shape: " + id);
        }
        return rows;
    }

    public static boolean has(String id) {
        return SHAPES.containsKey(id);
    }

    public static Set<String> ids() {
        return Collections.unmodifiableSet(SHAPES.keySet());
    }
